"""Generates a C++ model header from an ArcSim/arcilator state.json.

The state file is regenerated for every RTL build, so port offsets must never
be hardcoded in a harness. This emits a small, toolchain-independent header:

  namespace arcsim_model {
    constexpr const char kTopName[];
    constexpr size_t kStateBytes;
    constexpr bool kSettlesInOneEval;
    constexpr Port kPorts[];          // top-level inputs and outputs only
    void Eval(uint8_t*); void Initial(uint8_t*); void Final(uint8_t*);
  }
"""

import argparse
import json
import re
import sys

_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_$]*$")


def _symbol(name, what):
    if not name:
        return None
    if not _IDENT.match(name):
        raise ValueError("unexpected {} symbol name: {!r}".format(what, name))
    return name


def render(model):
    top = model["name"]
    eval_sym = _symbol(model.get("evalFnSym") or top + "_eval", "eval")
    initial_sym = _symbol(model.get("initialFnSym"), "initial")
    final_sym = _symbol(model.get("finalFnSym"), "final")

    ports = [
        s for s in model.get("states", [])
        if s.get("type") in ("input", "output")
    ]
    if not ports:
        raise ValueError("model {} exports no input/output ports".format(top))

    out = []
    out.append("// Generated by utils/arcsim/gen_ports.py. Do not edit.")
    out.append("#pragma once")
    out.append("#include <cstddef>")
    out.append("#include <cstdint>")
    out.append("")
    out.append('extern "C" void {}(uint8_t* state);'.format(eval_sym))
    if initial_sym:
        out.append('extern "C" void {}(uint8_t* state);'.format(initial_sym))
    if final_sym:
        out.append('extern "C" void {}(uint8_t* state);'.format(final_sym))
    out.append("")
    out.append("namespace arcsim_model {")
    out.append("")
    out.append("struct Port {")
    out.append("  const char* name;")
    out.append("  uint32_t offset;")
    out.append("  uint32_t bits;")
    out.append("  bool is_input;")
    out.append("};")
    out.append("")
    out.append("inline constexpr const char kTopName[] = {};".format(
        json.dumps(top)))
    out.append("inline constexpr size_t kStateBytes = {};".format(
        int(model["numStateBytes"])))
    out.append("inline constexpr bool kSettlesInOneEval = {};".format(
        "true" if model.get("settlesInOneEval") else "false"))
    out.append("")
    out.append("inline constexpr Port kPorts[] = {")
    for p in ports:
        out.append("    {{{}, {}, {}, {}}},".format(
            json.dumps(p["name"]), int(p["offset"]), int(p["numBits"]),
            "true" if p["type"] == "input" else "false"))
    out.append("};")
    out.append("inline constexpr size_t kNumPorts = {};".format(len(ports)))
    out.append("")
    out.append("inline void Eval(uint8_t* state) {{ ::{}(state); }}".format(
        eval_sym))
    out.append("inline void Initial(uint8_t* state) {{ {} }}".format(
        "::{}(state);".format(initial_sym) if initial_sym else "(void)state;"))
    out.append("inline void Final(uint8_t* state) {{ {} }}".format(
        "::{}(state);".format(final_sym) if final_sym else "(void)state;"))
    out.append("")
    out.append("}  // namespace arcsim_model")
    out.append("")
    return "\n".join(out)


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--state", required=True, help="state.json from arcsim")
    parser.add_argument("--top", required=True, help="top module name")
    parser.add_argument("--out", required=True, help="header to write")
    args = parser.parse_args(argv)

    with open(args.state) as f:
        models = json.load(f)
    if isinstance(models, dict):
        models = [models]
    matches = [m for m in models if m.get("name") == args.top]
    if len(matches) != 1:
        names = [m.get("name") for m in models]
        parser.error("expected exactly one model named {} in {}, found {}".format(
            args.top, args.state, names))

    text = render(matches[0])
    with open(args.out, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
